// Precompiles the client's validators from schemas/v1 (the source of truth) into
// src/generated/validators.ts: Ajv standalone code, bundled with its runtime helpers, so the
// client loads no schema files and compiles nothing at runtime (no eval: CSP and Workers allow it).
//   node scripts/validators.mjs           writes the file
//   generateValidators()                  returns its content (tests/validators.test.ts checks it's current)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";
import Ajv from "ajv";
import addFormats from "ajv-formats";
import standaloneCode from "ajv/dist/standalone/index.js";
import { build } from "esbuild";

const clientDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const schemasDir = path.join(clientDir, "..", "schemas", "v1");
export const outFile = path.join(clientDir, "src", "generated", "validators.ts");

const VALIDATORS = {
  validateChannelManifest: "channel-manifest.json",
  validateReleaseManifest: "release-manifest.json",
  validateCollection: "collection.json"
};

export async function generateValidators() {
  const ajv = new Ajv({ allErrors: true, code: { source: true } });
  addFormats(ajv);
  for (const file of Object.values(VALIDATORS)) {
    ajv.addSchema(JSON.parse(fs.readFileSync(path.join(schemasDir, file), "utf-8")), file);
  }
  const code = standaloneCode(ajv, VALIDATORS);

  // The standalone code is CommonJS and requires Ajv's runtime helpers and the formats; bundle
  // them into one ES module (resolved from the client's dependencies)
  const require = createRequire(path.join(clientDir, "package.json"));
  const result = await build({
    stdin: {
      contents: `import v from "./validators.cjs"; export const { ${Object.keys(VALIDATORS).join(", ")} } = v;`,
      resolveDir: clientDir,
      loader: "js"
    },
    plugins: [{
      name: "standalone",
      setup(b) {
        b.onResolve({ filter: /^\.\/validators\.cjs$/ }, () => ({ path: "validators.cjs", namespace: "standalone" }));
        b.onLoad({ filter: /.*/, namespace: "standalone" }, () => ({ contents: code, loader: "js", resolveDir: clientDir }));
        b.onResolve({ filter: /^(ajv|ajv-formats)\// }, (args) => ({ path: require.resolve(args.path) }));
      }
    }],
    bundle: true,
    format: "esm",
    platform: "neutral",
    mainFields: ["main"],
    legalComments: "none",
    write: false
  });
  const header = "// @ts-nocheck\n// Generated by scripts/validators.mjs from schemas/v1. Don't edit; run `pnpm --filter @usecds/client validators`.\n";
  return header + result.outputFiles[0].text;
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, await generateValidators());
  console.log(`wrote ${path.relative(process.cwd(), outFile)}`);
}
